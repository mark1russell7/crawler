#!/usr/bin/env node
// The roadmap file, made from the item files of the tracker page.
//
//   node scripts/roadmap.mjs                  write docs/ROADMAP.md from the item files
//   node scripts/roadmap.mjs --check          fail when docs/ROADMAP.md is not the file that the items make
//   node scripts/roadmap.mjs --items <dir>    read the item files from <dir>
//
// The tracker page is a view of a folder in the owner's private repository ~/git/fleet
// (artifacts/crawler-roadmap): db/items holds one file for each item. Change an item file there,
// write it to the page with the artifact-sync skill, then start this script.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const at = process.argv.indexOf("--items");
const ITEMS =
  at < 0
    ? join(homedir(), "git", "fleet", "artifacts", "crawler-roadmap", "db", "items")
    : resolve(process.argv[at + 1]);
const OUT = join(ROOT, "docs", "ROADMAP.md");

const STATUS = [
  ["waiting", "Waiting on Mark"],
  ["active", "In progress"],
  ["blocked", "Blocked"],
  ["later", "Later"],
  ["done", "Shipped"],
];
const AREA = {
  package: "Package",
  release: "Release and CI",
  jarvis: "jarvis",
  site: "Site and growth",
};

const items = readdirSync(ITEMS)
  .filter((name) => name.endsWith(".json"))
  .map((name) => {
    const item = JSON.parse(readFileSync(join(ITEMS, name), "utf8"));
    if (`${item.id}.json` !== name) throw new Error(`${name}: the id is ${item.id}`);
    if (!STATUS.some(([status]) => status === item.status))
      throw new Error(`${name}: unknown status ${item.status}`);
    if (!(item.area in AREA)) throw new Error(`${name}: unknown area ${item.area}`);
    return item;
  });
const ids = new Set(items.map((item) => item.id));
for (const item of items) {
  for (const dep of item.deps ?? [])
    if (!ids.has(dep)) throw new Error(`${item.id}: it waits for ${dep}, which is not an item`);
}

const out = [
  "# Roadmap",
  "",
  "This file is the roadmap of polite-crawler, its site, and the jarvis side that uses it.",
  "The tracker page shows the same items, with a dependency map and a timeline. `scripts/roadmap.mjs` makes this file from the item files of the tracker.",
  "Do not edit this file. Change the item file of the tracker, then start `pnpm roadmap`. Each item has an id, a status, an area, the items it waits for, dates and links.",
  "",
];
for (const [status, label] of STATUS) {
  const group = items.filter((item) => item.status === status);
  if (status === "done") {
    // The newest first. The sort of the order of the items breaks a tie of two dates.
    group.sort((a, b) => (b.shipped ?? "").localeCompare(a.shipped ?? "") || b.order - a.order);
  } else {
    group.sort((a, b) => a.order - b.order);
  }
  if (group.length === 0) continue;
  out.push(`## ${label}`, "");
  for (const item of group) {
    const title = item.title + (item.finding ? ` (${item.finding})` : "");
    out.push(`### \`${item.id}\`: ${title}`, "", item.summary, "");
    out.push(`- Area: ${AREA[item.area]}`);
    if (item.deps?.length)
      out.push(`- Waits for: ${item.deps.map((dep) => `\`${dep}\``).join(", ")}`);
    if (item.ask) out.push(`- What Mark does: ${item.ask}`);
    if (item.blockedBy) out.push(`- Blocked: ${item.blockedBy}`);
    if (item.owner) out.push(`- Owner: ${item.owner}`);
    if (item.started) out.push(`- Started: ${item.started}`);
    if (item.shipped) out.push(`- Shipped: ${item.shipped}`);
    for (const link of item.links ?? []) out.push(`- [${link.label}](${link.url})`);
    out.push("");
  }
}
out.push(
  "## Never",
  "",
  "Proxies, session rotation or stealth. They contradict the honest identity of the crawler, and courts treat them as circumvention.",
  "",
);
const text = out.join("\n");

if (process.argv.includes("--check")) {
  const now = readFileSync(OUT, "utf8");
  if (now !== text) {
    console.error(
      `docs/ROADMAP.md is not the file that ${ITEMS} makes. Start \`pnpm roadmap\`, then commit.`,
    );
    process.exit(1);
  }
  console.log(`docs/ROADMAP.md agrees with the ${items.length} items.`);
} else {
  writeFileSync(OUT, text);
  console.log(`docs/ROADMAP.md: ${items.length} items.`);
}
