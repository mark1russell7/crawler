#!/usr/bin/env node
// The roadmap file, made from the item files of the roadmap.
//
//   node scripts/roadmap.ts                  write docs/ROADMAP.md from the item files
//   node scripts/roadmap.ts --check          fail when docs/ROADMAP.md is not the file that the items make
//   node scripts/roadmap.ts --items <dir>    read the item files from <dir>
//
// The item files are kept outside this repository, one JSON file for each item. Give their folder
// with --items or in the variable ROADMAP_ITEMS. Change an item file there, then start this script.
// An item of the area `consumer` stays private: it is about a private user of the package, so this
// file leaves it out.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const at = process.argv.indexOf("--items");
const FOLDER = at < 0 ? process.env["ROADMAP_ITEMS"] : process.argv[at + 1];
if (FOLDER === undefined) throw new Error("Give the item folder: --items <dir> or ROADMAP_ITEMS.");
const ITEMS = resolve(FOLDER);
const OUT = join(ROOT, "docs", "ROADMAP.md");

const STATUS: ReadonlyArray<readonly [status: string, label: string]> = [
  ["waiting", "Waiting on Mark"],
  ["active", "In progress"],
  ["blocked", "Blocked"],
  ["later", "Later"],
  ["done", "Shipped"],
];
const AREA: Readonly<Record<string, string>> = {
  package: "Package",
  release: "Release and CI",
  consumer: "Private consumer",
  site: "Site and growth",
};

/** An item file of the roadmap: <id>.json. */
interface Item {
  readonly id: string;
  readonly title: string;
  readonly status: string;
  readonly area: string;
  readonly summary: string;
  readonly order: number;
  readonly finding?: string;
  readonly deps?: readonly string[];
  readonly ask?: string;
  readonly blockedBy?: string;
  readonly owner?: string;
  readonly started?: string;
  readonly shipped?: string;
  readonly links?: ReadonlyArray<{ readonly label: string; readonly url: string }>;
}

const all = readdirSync(ITEMS)
  .filter((name) => name.endsWith(".json"))
  .map((name) => {
    const item = JSON.parse(readFileSync(join(ITEMS, name), "utf8")) as Item;
    if (`${item.id}.json` !== name) throw new Error(`${name}: the id is ${item.id}`);
    if (!STATUS.some(([status]) => status === item.status))
      throw new Error(`${name}: unknown status ${item.status}`);
    if (!(item.area in AREA)) throw new Error(`${name}: unknown area ${item.area}`);
    return item;
  });
const ids = new Set(all.map((item) => item.id));
for (const item of all) {
  for (const dep of item.deps ?? [])
    if (!ids.has(dep)) throw new Error(`${item.id}: it waits for ${dep}, which is not an item`);
}
const items = all.filter((item) => item.area !== "consumer");
/** The owners that this file names. The line `Owner` of a different owner is not in this file. */
const PUBLIC_OWNERS: ReadonlySet<string> = new Set(["Mark"]);
const shown = new Set(items.map((item) => item.id));

const out = [
  "# Roadmap",
  "",
  "This file is the roadmap of polite-crawler and its site.",
  "`scripts/roadmap.ts` makes this file from the item files of the roadmap.",
  "Do not edit this file. Change the item file, then start `pnpm roadmap`. Each item has an id, a status, an area, the items it waits for, dates and links.",
  "",
];
for (const [status, label] of STATUS) {
  const group = items.filter((item) => item.status === status);
  if (status === "done") {
    // The newest first. The sort of the order of the items breaks a tie of two dates.
    group.sort((a, b) => (b.shipped ?? "").localeCompare(a.shipped ?? "") || b.order - a.order);
  } else {
    group.sort((a, b) => a.order - b.order);
  }
  if (group.length === 0) continue;
  out.push(`## ${label}`, "");
  for (const item of group) {
    const title = item.title + (item.finding ? ` (${item.finding})` : "");
    out.push(`### \`${item.id}\`: ${title}`, "", item.summary, "");
    out.push(`- Area: ${AREA[item.area] ?? item.area}`);
    const deps = (item.deps ?? []).filter((dep) => shown.has(dep));
    if (deps.length > 0) out.push(`- Waits for: ${deps.map((dep) => `\`${dep}\``).join(", ")}`);
    if (item.ask) out.push(`- What Mark does: ${item.ask}`);
    if (item.blockedBy) out.push(`- Blocked: ${item.blockedBy}`);
    if (item.owner && PUBLIC_OWNERS.has(item.owner)) out.push(`- Owner: ${item.owner}`);
    if (item.started) out.push(`- Started: ${item.started}`);
    if (item.shipped) out.push(`- Shipped: ${item.shipped}`);
    for (const link of item.links ?? []) out.push(`- [${link.label}](${link.url})`);
    out.push("");
  }
}
out.push(
  "## Never",
  "",
  "Proxies, session rotation or stealth. They contradict the honest identity of the crawler, and courts treat them as circumvention.",
  "",
);
const text = out.join("\n");

if (process.argv.includes("--check")) {
  const now = readFileSync(OUT, "utf8");
  if (now !== text) {
    console.error(
      `docs/ROADMAP.md is not the file that ${ITEMS} makes. Start \`pnpm roadmap\`, then commit.`,
    );
    process.exit(1);
  }
  console.log(`docs/ROADMAP.md agrees with the ${items.length} items.`);
} else {
  writeFileSync(OUT, text);
  console.log(`docs/ROADMAP.md: ${items.length} items.`);
}
